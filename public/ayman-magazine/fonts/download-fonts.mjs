// Self-host the magazine fonts. Run from the magazine folder:  node fonts/download-fonts.mjs
// Needs Node 18+ and an internet connection, once. After it finishes the magazine needs no external requests.
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Aref+Ruqaa:wght@400;700&family=Cormorant+Garamond:ital,wght@0,400;0,500;0,600;1,400&family=IBM+Plex+Sans+Arabic:wght@400;500;600&family=Markazi+Text:wght@400;500;600&family=Reem+Kufi:wght@400;500;600;700&display=swap";
// A modern browser user-agent makes Google return woff2 files split by script (arabic / latin ...).
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

const res = await fetch(CSS_URL, { headers: { "User-Agent": UA } });
if (!res.ok) throw new Error(`Google Fonts CSS request failed: ${res.status}`);
let css = await res.text();

const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]*)}/g)];
if (!blocks.length) throw new Error("No @font-face rules found in the Google Fonts response.");

await mkdir(here, { recursive: true });
let out = "/* Self-hosted magazine fonts (generated by download-fonts.mjs). Licence: SIL Open Font License 1.1 */\n";
let n = 0;
for (const [, subset, body] of blocks) {
  const family = body.match(/font-family:\s*'([^']+)'/)[1];
  const style = body.match(/font-style:\s*(\w+)/)[1];
  const weight = body.match(/font-weight:\s*(\d+)/)[1];
  const url = body.match(/url\(([^)]+)\)/)[1];
  const file = `${family.toLowerCase().replace(/\s+/g, "-")}-${subset}-${weight}${style === "italic" ? "-italic" : ""}.woff2`;
  const r = await fetch(url);
  if (!r.ok) throw new Error(`Font download failed: ${url}`);
  await writeFile(join(here, file), Buffer.from(await r.arrayBuffer()));
  out += `@font-face{${body.replace(/url\([^)]+\)/, `url("./${file}")`).trim()}}\n`;
  n++;
}
await writeFile(join(here, "fonts.css"), out);
console.log(`Saved ${n} font files and rewrote fonts/fonts.css — the magazine is now fully self-hosted.`);
